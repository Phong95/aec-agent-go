// A session written by the REAL Go store, with nested and non-sorted metadata,
// is a Go-written record whose bytes are pinned by a golden file. The file
// is compared with the generated bytes; refresh it from core/go with
// AEC_WIRE_UPDATE=1 go test ./components/persistence/ -run TestGoWritten (see
// the wiretest package doc: tests/testdata/golden is never rewritten from Go).
func TestGoWrittenSession(t *testing.T) {
	ctx := t.Context()
	store := persistence.NewMemorySessionStore(
		persistence.WithSessionClock(wiretest.Clock(1700000000000, 1)),
		persistence.WithSessionIDs(wiretest.IDs()),
	)

	inner := ordered.NewObject()
	inner.Set("y", 2)
	inner.Set("x", nil)
	nested := ordered.NewObject()
	nested.Set("b", []any{1, inner})
	nested.Set("a", "<&>")
	meta := ordered.NewObject() // no integer-like keys: JS would list those first
	meta.Set("zeta", 2.5)
	meta.Set("agentId", "go-agent")
	meta.Set("nested", nested)
	meta.Set("flag", true)
	meta.Set("count", 0)

	created, err := store.Create(ctx, meta)
	if err != nil {
		t.Fatal(err)
	}
	upd := created.Clone()
	upd.LLMModel = "claude-sonnet"
	cacheRead, cacheWrite, four := 10, 20, 4
	upd.CurrentTokenUsage = &kernel.TokenUsage{InputTokens: 1000, OutputTokens: 200, CacheReadTokens: &cacheRead, CacheWriteTokens: &cacheWrite}
	upd.CounterCalibration = &kernel.CounterCalibration{CharsPerToken: 3.5, Samples: 12}
	upd.ConsolidatedMessageCount = &four
	if err := store.Update(ctx, upd); err != nil {
		t.Fatal(err)
	}
	got, err := store.Get(ctx, created.ID)
	if err != nil || got == nil {
		t.Fatalf("Get = %v, %v", got, err)
	}
	b, err := kernel.EncodeJSON(got)
	if err != nil {
		t.Fatal(err)
	}
	wiretest.AssertGoWritten(t, "session.json", b)
}

// Three messages built in Go and written through the REAL Go message store are
// a Go-written history whose bytes are pinned by a golden file. The tool-call
// arguments are in non-sorted key order and carry raw <, > and &. One call carries
// an argumentsError built by llmhub.ParseToolArguments (Phase 8), which the store
// must keep as written.
func TestGoWrittenMessages(t *testing.T) {
	ctx := t.Context()
	store := persistence.NewMemoryMessageStore()

	a1, err := kernel.NewArguments([]byte(`{"path":"a<b>&c.csv","limit":10,"encoding":"utf8"}`))
	if err != nil {
		t.Fatal(err)
	}
	a2, err := kernel.NewArguments([]byte(`{"recursive":true,"path":"src"}`))
	if err != nil {
		t.Fatal(err)
	}
	badArgs, badErr := llmhub.ParseToolArguments(`{"path": "notes/report.md", "content": "He said "hi""}`)
	if badArgs != nil || badErr == "" {
		t.Fatalf("the bad arguments must give an argumentsError, got %q %q", badArgs, badErr)
	}
	isErr := true
	msgs := []kernel.Message{
		{Role: kernel.RoleUser, Content: "Open the <schedule> & sum it", Timestamp: "2026-10-01T08:00:00.000Z"},
		{
			Role: kernel.RoleAssistant, Content: "On it.", Timestamp: "2026-10-01T08:00:01.000Z",
			ToolCalls: []kernel.ToolCall{
				{ID: "call_1", Name: "read_file", Arguments: a1},
				{ID: "call_2", Name: "list_dir", Arguments: a2},
				{ID: "call_3", Name: "write_file", Arguments: badArgs, ArgumentsError: badErr},
			},
		},
		{
			Role: kernel.RoleTool, Content: "", Timestamp: "2026-10-01T08:00:02.000Z",
			ToolResults: []kernel.ToolResult{
				{ToolCallID: "call_1", Content: "boom", IsError: &isErr},
				{ToolCallID: "call_2", Content: "ok"},
			},
		},
	}
	for _, m := range msgs {
		if err := store.Append(ctx, "s", m); err != nil {
			t.Fatal(err)
		}
	}
	got, err := store.Get(ctx, "s")
	if err != nil {
		t.Fatal(err)
	}
	b, err := kernel.EncodeJSON(got)
	if err != nil {
		t.Fatal(err)
	}
	wiretest.AssertGoWritten(t, "messages.json", b)
}

