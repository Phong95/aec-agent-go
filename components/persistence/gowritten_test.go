// An artifact head record and its version log written through the REAL Go
// artifact store (create, then addVersion) is a Go-written record whose bytes are
// pinned by a golden file: the head is read back through Get and the versions
// through ListVersions, newest first.
func TestGoWrittenArtifactRecord(t *testing.T) {
	ctx := t.Context()
	store := persistence.NewMemoryArtifactStore()
	sha := strings.Repeat("a", 64)
	head1 := artifact.Artifact{
		ID: "go-art-1", AgentID: "go-agent", Name: "report.md", Type: "text/markdown", Description: "Weekly <report> & notes",
		Tags: []string{"b", "a"}, SessionID: "s1", Version: 1, SandboxPath: "artifacts/report.md", SandboxID: "docker:shared",
		Bytes: 10, SHA256: sha, CreatedAt: "2026-03-01T00:00:00.000Z", UpdatedAt: "2026-03-01T00:00:00.000Z",
	}
	v1 := artifact.Version{
		ArtifactID: "go-art-1", Version: 1, Bytes: 10, SHA256: sha, CreatedAt: "2026-03-01T00:00:00.000Z",
		Origin: artifact.Origin{AgentID: "go-agent", SessionID: "s1", Tool: "save_artifact", SandboxPath: "artifacts/report.md", SandboxID: "docker:shared"},
	}
	if err := store.Create(ctx, head1, v1); err != nil {
		t.Fatal(err)
	}
	sha2 := strings.Repeat("b", 64)
	head2 := head1.Clone()
	head2.Version, head2.Bytes, head2.SHA256, head2.UpdatedAt = 2, 11, sha2, "2026-03-02T00:00:00.000Z"
	v2 := artifact.Version{
		ArtifactID: "go-art-1", Version: 2, Bytes: 11, SHA256: sha2, CreatedAt: "2026-03-02T00:00:00.000Z", Note: "added a <cost> column",
		Origin: artifact.Origin{AgentID: "go-agent", SessionID: "s1", Tool: "update_artifact", SandboxPath: "artifacts/report.md", SandboxID: "docker:shared"},
	}
	if err := store.AddVersion(ctx, head2, v2); err != nil {
		t.Fatal(err)
	}
	head, err := store.Get(ctx, "go-art-1")
	if err != nil || head == nil {
		t.Fatalf("Get = %v, %v", head, err)
	}
	versions, err := store.ListVersions(ctx, "go-art-1")
	if err != nil {
		t.Fatal(err)
	}
	b, err := kernel.EncodeJSON(struct {
		Artifact artifact.Artifact  `json:"artifact"`
		Versions []artifact.Version `json:"versions"`
	}{*head, versions})
	if err != nil {
		t.Fatal(err)
	}
	wiretest.AssertGoWritten(t, "artifact-record.json", b)
}

// An artifact saved and then updated through the REAL Go artifact hub (over the
// real Go store and the aecmock in-memory sandbox) is a Go-written hub record
// pinned by a golden file: the head is read back with get,
// the versions with versions (newest first) and the list with list, and another
// agent's view must not find it. The clock and the ids are deterministic.
func TestGoWrittenArtifactHub(t *testing.T) {
	ctx := t.Context()
	store := persistence.NewMemoryArtifactStore()
	hub := artifacthub.NewArtifactHub(
		func() persistence.ArtifactStore { return store },
		artifacthub.WithClock(wiretest.Clock(1700000000000, 1000)),
		artifacthub.WithIDs(wiretest.IDs()),
	)
	view, err := hub.ForAgent("go-agent", "s1")
	if err != nil {
		t.Fatal(err)
	}
	fv, err := aecmock.NewInMemoryView("docker:shared", "go-agent")
	if err != nil {
		t.Fatal(err)
	}

	body := "# Weekly <report> & notes\n"
	saved, err := view.Save(ctx, artifact.SaveInput{
		Name: "reports/weekly.md", Type: "text/markdown", Content: &body,
		Description: "Weekly <report> & notes", Tags: []string{"b", "a", "b"}, Note: "first <cut>", Tool: "save_artifact",
	}, fv)
	if err != nil {
		t.Fatal(err)
	}
	// The file is rewritten outside the tool, then re-tracked: version 2.
	if _, err := fv.WriteFile(ctx, saved.Artifact.SandboxPath, "# Weekly report\nwith a <cost> column\n", sandboxhub.WriteOptions{}); err != nil {
		t.Fatal(err)
	}
	one := 1
	if _, err := view.Update(ctx, artifact.UpdateInput{
		Ref: artifact.Ref{Name: "reports/weekly.md"}, Note: "re-tracked", ExpectedVersion: &one, Tool: "update_artifact",
	}, fv); err != nil {
		t.Fatal(err)
	}

	head, err := view.Get(ctx, artifact.Ref{Name: "reports/weekly.md"})
	if err != nil {
		t.Fatal(err)
	}
	versions, err := view.Versions(ctx, artifact.Ref{Name: "reports/weekly.md"})
	if err != nil {
		t.Fatal(err)
	}
	if head.Version != 2 || len(versions) != 2 {
		t.Fatalf("head version %d with %d versions, want 2 and 2", head.Version, len(versions))
	}
	b, err := kernel.EncodeJSON(struct {
		Artifact artifact.Artifact  `json:"artifact"`
		Versions []artifact.Version `json:"versions"`
	}{head, versions})
	if err != nil {
		t.Fatal(err)
	}
	wiretest.AssertGoWritten(t, "artifact-hub.json", b)
}

