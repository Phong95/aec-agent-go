// The exported API of the root package is pinned by tests/testdata/api/aec.txt (since
// 2026-10-04). Any change to the root API (a name added, removed or renamed, a
// signature changed) changes the snapshot and shows up in review as a diff of that file.
//
// Refresh the snapshot after an intended change with:
//
//	go test -run TestAPISnapshot -update .

var updateAPISnapshot = flag.Bool("update", false, "rewrite tests/testdata/api/aec.txt from the root package (TestAPISnapshot)")

const apiSnapshotPath = "tests/testdata/api/aec.txt"

const apiSnapshotHeader = `# Exported API of the root package aec (github.com/Phong95/aec-agent-go).
# Generated by TestAPISnapshot (api_snapshot_test.go); do not edit by hand.
# Refresh after an intended API change: go test -run TestAPISnapshot -update .
`

// TestAPISnapshot lists every exported identifier of the root package (constants,
// variables, types with their exported fields or methods, functions, and the exported
// methods of exported root types) with its kind and declaration, and compares the list
// with tests/testdata/api/aec.txt.
func TestAPISnapshot(t *testing.T) {
	got := apiSnapshotHeader + strings.Join(rootAPI(t), "\n") + "\n"
	if *updateAPISnapshot {
		if err := os.MkdirAll(filepath.Dir(apiSnapshotPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(apiSnapshotPath, []byte(got), 0o644); err != nil { //nolint:gosec // a checked-in text file
			t.Fatal(err)
		}
		return
	}
	data, err := os.ReadFile(apiSnapshotPath)
	if err != nil {
		t.Fatalf("read %s: %v (create it with: go test -run TestAPISnapshot -update .)", apiSnapshotPath, err)
	}
	want := strings.ReplaceAll(string(data), "\r\n", "\n")
	if got == want {
		return
	}
	gotLines, wantLines := strings.Split(got, "\n"), strings.Split(want, "\n")
	for _, l := range wantLines {
		if !slices.Contains(gotLines, l) {
			t.Errorf("removed from the root API: %s", l)
		}
	}
	for _, l := range gotLines {
		if !slices.Contains(wantLines, l) {
			t.Errorf("added to the root API: %s", l)
		}
	}
	t.Errorf("the root API differs from %s; if the change is intended, run: go test -run TestAPISnapshot -update .", apiSnapshotPath)
}

// rootAPI parses the non-test .go files of the root package and returns one sorted line per
// exported declaration.
func rootAPI(t *testing.T) []string {
	t.Helper()
	files, err := filepath.Glob("*.go")
	if err != nil {
		t.Fatal(err)
	}
	fset := token.NewFileSet()
	var lines []string
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, file, nil, 0)
		if err != nil {
			t.Fatalf("parse %s: %v", file, err)
		}
		for _, decl := range f.Decls {
			lines = append(lines, apiLines(t, fset, decl)...)
		}
	}
	if len(lines) == 0 {
		t.Fatal("the root package declares no exported identifier")
	}
	slices.Sort(lines)
	return lines
}

// apiLines renders the exported part of one top-level declaration.
func apiLines(t *testing.T, fset *token.FileSet, decl ast.Decl) []string {
	t.Helper()
	switch d := decl.(type) {
	case *ast.FuncDecl:
		if !d.Name.IsExported() {
			return nil
		}
		fn := &ast.FuncDecl{Recv: d.Recv, Name: d.Name, Type: d.Type}
		if d.Recv == nil {
			return []string{"func " + strings.TrimPrefix(render(t, fset, fn), "func ")}
		}
		recv := receiverType(d.Recv.List[0].Type)
		if !ast.IsExported(strings.TrimPrefix(recv, "*")) {
			return nil
		}
		// The receiver name is not part of the API: print the method with the bare receiver type.
		sig := render(t, fset, &ast.FuncDecl{Name: d.Name, Type: d.Type})
		return []string{"method (" + recv + ") " + strings.TrimPrefix(sig, "func ")}
	case *ast.GenDecl:
		var out []string
		for _, spec := range d.Specs {
			switch s := spec.(type) {
			case *ast.TypeSpec:
				if s.Name.IsExported() {
					out = append(out, typeLines(t, fset, s)...)
				}
			case *ast.ValueSpec:
				for i, n := range s.Names {
					if !n.IsExported() {
						continue
					}
					out = append(out, valueLine(t, fset, d.Tok, s, i))
				}
			}
		}
		return out
	default:
		return nil
	}
}

// typeLines renders a type declaration: an alias or a non-struct, non-interface type in one
// line, a struct with one line per exported field and an interface with one line per method.
func typeLines(t *testing.T, fset *token.FileSet, s *ast.TypeSpec) []string {
	t.Helper()
	name := s.Name.Name
	if s.TypeParams != nil {
		name = s.Name.Name + "[" + typeParams(t, fset, s.TypeParams) + "]"
	}
	if s.Assign.IsValid() {
		return []string{"type " + name + " = " + render(t, fset, s.Type)}
	}
	switch ty := s.Type.(type) {
	case *ast.StructType:
		out := []string{"type " + name + " struct"}
		for _, f := range ty.Fields.List {
			typ := render(t, fset, f.Type)
			if len(f.Names) == 0 { // an embedded field
				if ast.IsExported(strings.TrimPrefix(receiverType(f.Type), "*")) {
					out = append(out, "field "+s.Name.Name+" embeds "+typ)
				}
				continue
			}
			for _, n := range f.Names {
				if n.IsExported() {
					out = append(out, "field "+s.Name.Name+"."+n.Name+" "+typ)
				}
			}
		}
		return out
	case *ast.InterfaceType:
		out := []string{"type " + name + " interface"}
		for _, m := range ty.Methods.List {
			if len(m.Names) == 0 {
				out = append(out, "method "+s.Name.Name+" embeds "+render(t, fset, m.Type))
				continue
			}
			for _, n := range m.Names {
				if n.IsExported() {
					out = append(out, "method "+s.Name.Name+"."+n.Name+strings.TrimPrefix(render(t, fset, m.Type), "func"))
				}
			}
		}
		return out
	default:
		return []string{"type " + name + " " + render(t, fset, s.Type)}
	}
}

// valueLine renders one name of a const or var spec: its explicit type, else its value (for
// a composite literal, the literal's type, so a struct variable shows its fields and not its
// values).
func valueLine(t *testing.T, fset *token.FileSet, tok token.Token, s *ast.ValueSpec, i int) string {
	t.Helper()
	line := tok.String() + " " + s.Names[i].Name
	if s.Type != nil {
		line += " " + render(t, fset, s.Type)
	}
	if i < len(s.Values) {
		if lit, ok := s.Values[i].(*ast.CompositeLit); ok && s.Type == nil && lit.Type != nil {
			return line + " " + render(t, fset, lit.Type)
		}
		line += " = " + render(t, fset, s.Values[i])
	}
	return line
}

// typeParams renders a type parameter list without its brackets.
func typeParams(t *testing.T, fset *token.FileSet, fl *ast.FieldList) string {
	t.Helper()
	parts := make([]string, 0, len(fl.List))
	for _, f := range fl.List {
		names := make([]string, 0, len(f.Names))
		for _, n := range f.Names {
			names = append(names, n.Name)
		}
		parts = append(parts, strings.Join(names, ", ")+" "+render(t, fset, f.Type))
	}
	return strings.Join(parts, ", ")
}

// receiverType renders a receiver or embedded field type as Name or *Name, without type
// arguments.
func receiverType(e ast.Expr) string {
	switch x := e.(type) {
	case *ast.StarExpr:
		return "*" + receiverType(x.X)
	case *ast.Ident:
		return x.Name
	case *ast.IndexExpr:
		return receiverType(x.X)
	case *ast.IndexListExpr:
		return receiverType(x.X)
	case *ast.SelectorExpr:
		return x.Sel.Name
	default:
		return ""
	}
}

var apiSpace = regexp.MustCompile(`\s*\n\s*`)

// apiTabs matches the alignment padding go/printer puts between a struct field and its type.
var apiTabs = regexp.MustCompile(`[ \t]*\t[ \t]*`)

// render prints a node with go/printer on one line: the line breaks of a multi-line node
// (a struct type) become "; " and the alignment tabs one space.
func render(t *testing.T, fset *token.FileSet, node any) string {
	t.Helper()
	var b bytes.Buffer
	if err := printer.Fprint(&b, fset, node); err != nil {
		t.Fatalf("print: %v", err)
	}
	s := apiSpace.ReplaceAllString(b.String(), "; ")
	s = apiTabs.ReplaceAllString(s, " ")
	s = strings.ReplaceAll(s, "{; ", "{ ")
	return strings.ReplaceAll(s, "; }", " }")
}
